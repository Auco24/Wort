/** Picks the translation in the learner's language, falling back to the closest available one. */
export function starterDrafts(deck: StarterDeck, native: UiLang): CardDraft[] {
  const japanese = deck.language === 'ja';
  return deck.rows.map(([term, extra, pos, ru, en, de, forms, example]) => {
    const tr = { ru, en, de };
    const translation = tr[native] || (native === 'de' ? en : '') || en || ru || de;
    return {
      term,
      translation,
      article: !japanese && extra ? extra : undefined,
      reading: japanese && extra ? extra : undefined,
      pos,
      forms: forms || undefined,
      example: example || undefined,
      tags: ['starter'],
    };
  });
}
